"""Scan dimension linking: auto-link rate, Ø leaders, chain segments.

Runs the real pipeline on the deterministic synthetic scan
(``data/examples/real/scan_test.png`` — regenerated by the committed
generator, see docs/BENCHMARK.md). Asserts the linking fixes, not just
"does not crash": ≥50 % auto-linked, Ø callouts bound to their leaders,
chain LINEAR dims linked to sequential segments.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from core.cad_builder import build_solid
from core.models import ElementType, Symbol
from core.ocr_gost import recognize_dimensions
from core.scan_pipeline import parse_scan

REAL_DIR = Path(__file__).resolve().parent.parent / "data" / "examples" / "real"
SCAN_PATH = REAL_DIR / "scan_test.png"
SCAN_GT_PATH = REAL_DIR / "scan_test_ground_truth.json"


@pytest.fixture(scope="module")
def scan_drawing():
    from data.examples.real.generate_real_examples import gen_scan

    gen_scan()  # deterministic (seeded) — rewrites the gitignored scan PNG
    return parse_scan(SCAN_PATH)


@pytest.fixture(scope="module")
def scan_dims(scan_drawing):
    return recognize_dimensions(scan_drawing)


def test_scan_auto_link_rate_at_least_half(scan_dims):
    linked = [d for d in scan_dims if d.linked_element_id]
    assert len(linked) / len(scan_dims) >= 0.5, (
        f"auto-linked only {len(linked)}/{len(scan_dims)} dimensions")


def test_diameter_dims_linked_to_leaders_not_random_contour(scan_drawing, scan_dims):
    elements = {e.id: e for e in scan_drawing.elements}
    dia = [d for d in scan_dims if d.symbol is Symbol.DIAMETER]
    assert dia, "expected Ø dimensions on the scan"
    for d in dia:
        assert d.linked_element_id, f"{d.raw_text} is not linked at all"
        el = elements.get(d.linked_element_id)
        assert el is not None, f"{d.raw_text} links to a missing element"
        # the leader is a DIMENSION_LINE (or, at worst, the axis) — never a
        # part-outline CONTOUR and never TEXT/HATCH
        assert el.type in (ElementType.DIMENSION_LINE, ElementType.AXIS), \
            f"{d.raw_text} linked to {el.type.name}, not a leader/axis"
        if el.type is ElementType.DIMENSION_LINE and len(el.points) == 2:
            (x0, _y0), (x1, _y1) = el.points
            # GOST Ø leaders are square-on: vertical, x ≈ the text centre
            el_cx = (x0 + x1) / 2.0
            assert abs(el_cx - d.anchor[0]) < 8.0  # mm


def test_chain_dimensions_linked_sequentially(scan_dims):
    by_text = {d.raw_text: d for d in scan_dims}
    for text, seg in (("80", "#seg0"), ("60", "#seg1"), ("100", "#seg2")):
        d = by_text[text]
        assert d.linked_element_id is not None, f"{text} not linked"
        assert d.linked_element_id.endswith(seg), \
            f"{text} should link to sequential segment {seg}, got {d.linked_element_id}"


def test_outline_strokes_not_reclassified(scan_drawing):
    """Revolution surfaces keep their class — never DIMENSION_LINE.

    Every long horizontal stroke inside the main contour (boss/journal
    surfaces, bore walls) must remain CONTOUR; dimension strokes live below
    the outline or ride the axis/leader rows.
    """
    from core.scan_linking import main_contour_bbox

    elements = scan_drawing.elements
    bbox = main_contour_bbox(elements)
    assert bbox is not None
    x0, y0, x1, y1 = bbox

    def inside(e) -> bool:
        (ax, ay), (bx, by) = e.points
        return not (max(ax, bx) < x0 or min(ax, bx) > x1
                    or max(ay, by) < y0 or min(ay, by) > y1)

    surfaces = [
        e for e in elements
        if len(e.points) == 2
        and abs(e.points[0][1] - e.points[1][1]) <= 0.6  # horizontal, mm
        and (max(e.points[0][0], e.points[1][0]) - min(e.points[0][0], e.points[1][0])) > 50.0
        and inside(e)
    ]
    assert surfaces, "expected revolution surface strokes inside the main contour"
    for e in surfaces:
        assert e.type is not ElementType.DIMENSION_LINE, (
            f"surface stroke {e.id} was reclassified to DIMENSION_LINE")


def test_zero_led_diameters_stay_uncertain(scan_dims):
    """Zero-led Ø reads (RapidOCR drops the Ø glyph) must never auto-apply."""
    for raw in ("060", "040", "030", "012"):
        d = next(x for x in scan_dims if x.raw_text == raw)
        assert d.is_uncertain, f"{raw} must stay uncertain until the user confirms"


def test_scan_volume_matches_ground_truth(scan_drawing):
    gt = json.loads(SCAN_GT_PATH.read_text(encoding="utf-8"))
    solid = build_solid(scan_drawing.profile, bore_diameter=scan_drawing.bore_diameter)
    assert solid.val().Volume() == pytest.approx(gt["expected_volume_mm3"], rel=0.01)


def test_scan_solver_produces_no_error_contradictions(scan_drawing, scan_dims):
    """The raster profile erodes stroke endpoints (~10 px/side at 200 DPI),
    so the scan path must verify lengths with pixel-derived tolerances —
    and then report zero blocking contradictions."""
    from core.constraint_solver import (
        scan_diameter_tol_mm,
        scan_linear_tol_mm,
        solve_constraints,
    )

    dpi = 200.0
    assert scan_linear_tol_mm(dpi) == pytest.approx(24.0 * 25.4 / 200.0)
    _, contradictions = solve_constraints(
        scan_dims, scan_drawing.profile, bore_diameter=scan_drawing.bore_diameter,
        linear_tol_mm=scan_linear_tol_mm(dpi),
        diameter_tol_mm=scan_diameter_tol_mm(dpi))
    errors = [c for c in contradictions if c.severity == "error"]
    assert not errors, "scan produced blocking contradictions: " + "; ".join(
        c.message for c in errors)


def test_scan_chain_sum_is_consistent(scan_dims):
    """80 + 60 + 100 must equal the printed overall length 240 — the chain
    segments came from one merged dimension line."""
    linear = {d.raw_text: d.value for d in scan_dims if d.symbol.name == "LINEAR"}
    assert linear["80"] + linear["60"] + linear["100"] == pytest.approx(linear["240"])
